// ── Daily experiment ───────────────────────────────────────────────────────────
// Same game + same seed for everyone on the same calendar day (local date).

const EPOCH = Date.UTC(2026, 0, 1);

export function dailyKey(d = new Date()) {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

export function dailyNo(d = new Date()) {
  return Math.floor((Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) - EPOCH) / 86400000) + 1;
}

/**
 * The daily rotation is frozen to the original nine experiments, in this order. Adding a new game
 * must not silently change which experiment any past or future date selects. (Versioned: v1.)
 */
export const DAILY_POOL = ['zero', 'exact', 'loop', 'draw', 'stop', 'balance', 'drift', 'echo', 'center'] as const;

export function dailyGame(d = new Date()) {
  // A stride of 4 (coprime with 9) so consecutive days feel different.
  const n = dailyNo(d);
  const L = DAILY_POOL.length;
  return byId(DAILY_POOL[(((n * 4) % L) + L) % L])!;
}

export function dailySeed(d = new Date()) {
  let h = 2166136261;
  const s = 'epsilon/' + dailyKey(d);
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

