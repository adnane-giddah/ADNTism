// ── Levels ─────────────────────────────────────────────────────────────────────
// Records are kept per level. Medium keeps the bare id so older records still count.
export const recId = (id: string, level: Level, mode?: string) => {
  const g = byId(id);
  const m = mode && g?.modes && mode !== g.modes[0].id ? `~${mode}` : '';
  return (level === 'medium' ? id : `${id}.${level}`) + m;
};

export function savedMode(id: string): string | undefined {
  const g = byId(id);
  if (!g?.modes) return undefined;
  try {
    const v = localStorage.getItem('eps:mode:' + id);
    if (v && g.modes.some((m) => m.id === v)) return v;
  } catch {
    /* ignore */
  }
  return g.modes[0].id;
}

export function saveMode(id: string, m: string) {
  try {
    localStorage.setItem('eps:mode:' + id, m);
  } catch {
    /* ignore */
  }
}
